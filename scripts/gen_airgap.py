#!/usr/bin/env python3
"""Generates everything the enclave (mode B2) needs to match the Argo CD applications in platform/apps.

Argo CD in the enclave cannot reach a Helm repository. Following Zarf's documented Argo CD pattern, each chart is
carried as an OCI artefact and each Application names it as `oci://<registry>/charts/<chart>`; the Zarf agent
rewrites the registry host to the enclave registry, and git URLs to the enclave git server.

Writes:
  platform/overlays/b2/oci-charts/kustomization.yaml   patches every Helm source to its OCI form
  airgap/charts.txt                                    chart, repository, version: input to airgap/push-charts.sh
  airgap/zarf/zarf.yaml, airgap/zarf-langsmith/zarf.yaml  package definitions
  airgap/zarf/images-platform.txt, images-langsmith.txt (only with --rendered DIR) images found in the rendered charts

Usage: gen_airgap.py [--rendered out/rendered-b2]
CI runs it and fails if any generated file differs from what is committed.
"""
from __future__ import annotations

import pathlib
import re
import sys

import yaml

ROOT = pathlib.Path(__file__).resolve().parent.parent
APPS = ROOT / "platform" / "apps"
ZARF = ROOT / "airgap" / "zarf"
LANGSMITH_PKG = ROOT / "airgap" / "zarf-langsmith"
# Placeholder host. It never resolves: the Zarf agent replaces it with the enclave registry at admission.
OCI_HOST = "chart-registry.invalid"
# Set when the package is built: zarf package create --set CHART_REGISTRY=<registry holding the pushed charts>
TMPL_REGISTRY = "###ZARF_PKG_TMPL_CHART_REGISTRY###"
# Application files carry this placeholder for "this repository"; platform/overlays/release replaces it (and the
# placeholder revision) with the repository and release tag every installation syncs from.
PLACEHOLDER_REPO = "https://git.invalid/platform.git"
RELEASE = ROOT / "platform" / "overlays" / "release" / "kustomization.yaml"
HEADER = "# Generated by scripts/gen_airgap.py from platform/apps. Do not edit by hand.\n"
HELM_TEST = re.compile(r"helm\.sh/hook\"?:\s*\"?test")
IMAGE_LINE = re.compile(r"^\s*-?\s*(?:image|imageName):\s*[\"']?([^\s\"'#]+)", re.M)


def release_source() -> tuple[str, str]:
    """The repository URL and release revision from the release component's two replacements. Each replacement is
    identified by the field it writes (repoURL or targetRevision), not by its position."""
    if not RELEASE.exists():
        raise SystemExit(f"{RELEASE.relative_to(ROOT)} is missing: it names the repository and release to carry in")
    found = {}
    for replacement in yaml.safe_load(RELEASE.read_text())["replacements"]:
        paths = [path for target in replacement["targets"] for path in target["fieldPaths"]]
        for field in ("repoURL", "targetRevision"):
            if any(path.endswith(field) for path in paths):
                found[field] = str(replacement["sourceValue"])
    if set(found) != {"repoURL", "targetRevision"}:
        raise SystemExit(f"{RELEASE.relative_to(ROOT)}: expected one repoURL and one targetRevision replacement")
    return found["repoURL"], found["targetRevision"]


def applications() -> list[dict]:
    docs = []
    for path in sorted(APPS.glob("*.yaml")):
        docs += [d for d in yaml.safe_load_all(path.read_text()) if d and d.get("kind") == "Application"]
    return docs


def sources(app: dict) -> list[tuple[str, dict]]:
    spec = app["spec"]
    if "sources" in spec:
        return [(f"/spec/sources/{i}", src) for i, src in enumerate(spec["sources"])]
    return [("/spec/source", spec["source"])]


class _Dumper(yaml.SafeDumper):
    pass


_Dumper.add_representer(str, lambda dumper, value: dumper.represent_scalar(
    "tag:yaml.org,2002:str", value, style="|" if "\n" in value else None))


def dump(data) -> str:
    return yaml.dump(data, Dumper=_Dumper, sort_keys=False, default_flow_style=False, width=1000)


def qualified(image: str) -> bool:
    return "/" in image and "." in image.split("/")[0] and "{{" not in image


def images_in(text: str) -> set[str]:
    """Images named in rendered YAML. Helm test hooks are never run by Argo CD, so their images are not carried."""
    documents = [doc for doc in re.split(r"^---\s*$", text, flags=re.M) if not HELM_TEST.search(doc)]
    return {m for doc in documents for m in IMAGE_LINE.findall(doc) if qualified(m)}


def floating(image: str) -> bool:
    name = image.split("@")[0]
    return "@" not in image and (":" not in name.split("/")[-1] or name.endswith(":latest"))


def read_list(path: pathlib.Path) -> list[str]:
    if not path.exists():
        return []
    return [line.split("#")[0].strip() for line in path.read_text().splitlines() if line.split("#")[0].strip()]


def main() -> int:
    rendered = pathlib.Path(sys.argv[sys.argv.index("--rendered") + 1]) if "--rendered" in sys.argv else None
    this_repo, release = release_source()
    charts: list[tuple[str, str, str, str]] = []  # app, chart, repo, version
    git_repos: set[str] = set()
    patches = []
    for app in applications():
        name = app["metadata"]["name"]
        ops = []
        for pointer, src in sources(app):
            if "chart" in src:
                charts.append((name, src["chart"], src["repoURL"], str(src["targetRevision"])))
                ops += [
                    {"op": "replace", "path": f"{pointer}/repoURL", "value": f"oci://{OCI_HOST}/charts/{src['chart']}"},
                    {"op": "remove", "path": f"{pointer}/chart"},
                    {"op": "add", "path": f"{pointer}/path", "value": "."},
                ]
            elif src["repoURL"] not in (PLACEHOLDER_REPO, this_repo):
                git_repos.add(f"{src['repoURL']}@{src['targetRevision']}")
        if ops:
            patches.append({"target": {"kind": "Application", "name": name}, "patch": dump(ops)})

    component = {"apiVersion": "kustomize.config.k8s.io/v1alpha1", "kind": "Component", "patches": patches}
    out = ROOT / "platform" / "overlays" / "b2" / "oci-charts"
    out.mkdir(parents=True, exist_ok=True)
    (out / "kustomization.yaml").write_text(HEADER + "---\n" + dump(component))

    (ROOT / "airgap" / "charts.txt").write_text(
        HEADER + "# chart repository version\n" + "".join(f"{c} {r} {v}\n" for _, c, r, v in charts))

    if rendered:
        platform, langsmith = set(), set()
        for path in sorted(rendered.glob("[a-z]*.yaml")):
            (langsmith if path.stem == "langsmith" else platform).update(images_in(path.read_text()))
        for path in sorted((ROOT / "platform" / "manifests").rglob("*.yaml")):
            platform.update(images_in(path.read_text()))
        for filename, found in (("images-platform.txt", platform - langsmith), ("images-langsmith.txt", langsmith)):
            (ZARF / filename).write_text(HEADER + "".join(f"{image}\n" for image in sorted(found)))

    def chart_refs(select) -> list[str]:
        return [f"{TMPL_REGISTRY}/charts/{c}:{v}" for app, c, _, v in charts if select(app)]

    versions = yaml.safe_load((ROOT / "versions.yaml").read_text())
    argo_chart = str(next(v for group in versions.values() if isinstance(group, dict)
                          for k, v in group.items() if k == "argo-cd-chart"))
    platform_pkg = {
        "kind": "ZarfPackageConfig",
        "metadata": {
            "name": "dp-ai-001-c-platform",
            "version": "0.2.0",
            "description": "Innovox sovereign agentic platform, open-source layer, for carry-in to a "
                           "disconnected enclave (B2)",
        },
        "components": [
            {"name": "gitops-source", "required": True,
             "description": "This repository and the other git sources Argo CD reads, mirrored into the enclave "
                            "git server",
             "repos": [f"{this_repo}@{release}", *sorted(git_repos)]},
            {"name": "argo-cd", "required": True,
             "description": "Argo CD is the one chart Zarf installs itself; Argo CD then syncs everything else",
             "charts": [{"name": "argo-cd", "version": argo_chart, "url": "https://argoproj.github.io/argo-helm",
                         "namespace": "argocd", "releaseName": "argocd",
                         "valuesFiles": ["../../platform/values/argocd/values.yaml"]}]},
            {"name": "platform-charts", "required": True,
             "description": "Helm charts as OCI artefacts, at the versions in platform/apps",
             "images": chart_refs(lambda app: app != "langsmith")},
            {"name": "platform-images", "required": True,
             "description": "Images found in the rendered charts and manifests (images-platform.txt) and images "
                            "that operators pull at run time (images-extra.txt)",
             "images": sorted(set(read_list(ZARF / "images-platform.txt") + read_list(ZARF / "images-extra.txt")))},
        ],
    }
    langsmith_pkg = {
        "kind": "ZarfPackageConfig",
        "metadata": {
            "name": "dp-ai-001-c-langsmith",
            "version": next(v for app, _, _, v in charts if app == "langsmith"),
            "description": "LangSmith chart and images, packaged apart so it follows LangChain's release cadence "
                           "(AD-40). Needs an offline licence from LangChain (D-06).",
        },
        "components": [
            {"name": "langsmith", "required": True,
             "images": chart_refs(lambda app: app == "langsmith")
             + sorted(set(read_list(ZARF / "images-langsmith.txt") + read_list(ZARF / "images-langsmith-extra.txt")))},
        ],
    }
    (ZARF / "zarf.yaml").write_text(HEADER + "---\n" + dump(platform_pkg))
    LANGSMITH_PKG.mkdir(parents=True, exist_ok=True)
    (LANGSMITH_PKG / "zarf.yaml").write_text(HEADER + "---\n" + dump(langsmith_pkg))
    carried = platform_pkg["components"][3]["images"] + langsmith_pkg["components"][0]["images"]
    bad = sorted(image for image in carried if floating(image))
    for image in bad:
        print(f"ERROR floating tag, cannot be carried in or admitted: {image}")
    if bad:
        return 1
    print(f"{len(charts)} charts, {len(git_repos) + 1} git sources, "
          f"{len(platform_pkg['components'][3]['images'])} platform images, "
          f"{len(langsmith_pkg['components'][0]['images']) - 1} LangSmith images")
    return 0


if __name__ == "__main__":
    sys.exit(main())
